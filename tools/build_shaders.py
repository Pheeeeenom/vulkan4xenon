#!/usr/bin/env python3
"""Compile GLSL shaders for a vulkan4xenon app: each to Vulkan SPIR-V with glslang, then to a Xenos container with
xost. Writes a C source and header holding each shader's SPIR-V, for the app to hand vkCreateShaderModule, and
v4x_shader_bundle, which the layer looks the SPIR-V up in.

    build_shaders.py --xost ../Xbox-360-SDK/xenos-toolchain --output tests/shaders tests/shaders/triangle.vert ...

--optimize has xost rewrite each program's instructions first (xost:xasm/optimize.py): fewer instructions, the same
results.

The layer's own shaders go in a bundle of their own, their symbols prefixed:

    build_shaders.py --xost ... --output src/blit_shaders --bundle v4x_blit_bundle --prefix v4x_ src/shaders/blit.*

glslang defaults to xost's copy (tools/glslang/bin/glslang.exe under --xost). Run it from the repository root, so
paths stay relative and work for a Windows glslang from WSL too.
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

# include/vulkan4xenon.h's V4X_RESOURCE_* kinds.
RESOURCE_KINDS = {"push": "V4X_RESOURCE_PUSH_CONSTANTS", "uniform": "V4X_RESOURCE_UNIFORM_BUFFER",
                  "sampler": "V4X_RESOURCE_SAMPLER"}
DEFAULT_BUNDLE = "v4x_shader_bundle"
FNV_OFFSET_BASIS = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
WORDS_PER_LINE = 6


def fnv1a_64(data):
    """The layer's hash of SPIR-V (src/shader.c): FNV-1a over the bytes of each word, low byte first."""
    value = FNV_OFFSET_BASIS
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def compile_spirv(glslang, source, directory):
    output = Path(os.path.relpath(directory)) / (source.name + ".spv")
    result = subprocess.run([str(glslang), "-V", str(source), "-o", str(output)], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"glslang failed on {source}:\n{result.stdout}{result.stderr}")
    return output.read_bytes()


def lower(xost, spirv_bytes, source, optimize=False):
    """The container, xost's pooled literals, and where its blocks and samplers landed."""
    sys.path.insert(0, str(xost))
    from xasm.program import XSDK_REGISTERS
    from xsc import spirv
    from xsc.lower import lower_ex
    from xsc.resolve import resolve_interface

    interface = resolve_interface(spirv.Module.parse(spirv_bytes))
    resources = [(b.kind, b.descriptor_set or 0, b.binding or 0, b.reg, b.regs) for b in interface.blocks]
    resources += [("sampler", v.descriptor_set or 0, v.binding or 0, slot, 1) for v, slot in interface.samplers]
    # The layer runs on xsdk, whose set-up gives each kind of shader 64 registers (xsdk:src/gpu_setup.c); xost
    # refuses a shader past its kind's share, which would hang the GPU.
    container, manifest = lower_ex(spirv.Module.parse(spirv_bytes), XSDK_REGISTERS, optimize)
    literals = []
    for entry in manifest:
        if len(entry) != 2:
            sys.exit(f"{source}: xost wants a constant the layer doesn't set yet: {entry}")
        literals.append(entry)
    return container, literals, resources


def c_name(source, prefix):
    return prefix + source.name.replace(".", "_")


def words_array(name, words, qualifier="static const"):
    lines = [f"{qualifier} uint32_t {name}[] = {{"]
    for i in range(0, len(words), WORDS_PER_LINE):
        lines.append("\t" + ", ".join(f"0x{w:08X}" for w in words[i:i + WORDS_PER_LINE]) + ",")
    lines.append("};")
    return lines


def float_literal(value):
    return f"{float(value)!r}f"


def write_outputs(output, shaders, sources, bundle):
    header_guard = f"V4X_{output.name.upper()}_H"
    generated = f"// Generated by tools/build_shaders.py from {len(sources)} shaders; don't edit."
    header = [generated, f"#ifndef {header_guard}", f"#define {header_guard}", "", "#include <stdint.h>", ""]
    # vulkan4xenon.h declares the app's bundle; another bundle is declared here.
    if bundle != DEFAULT_BUNDLE:
        header[-1:-1] = ['', '#include "vulkan4xenon.h"']
        header += [f"extern const V4xShaderBundle {bundle};", ""]
    source = [generated, f'#include "{output.name}.h"', "", '#include "vulkan4xenon.h"', ""]
    entries = []
    for shader in shaders:
        name = shader["name"]
        spirv_words = list(struct.unpack(f"<{len(shader['spirv']) // 4}I", shader["spirv"]))
        container_words = list(struct.unpack(f">{len(shader['container']) // 4}I", shader["container"]))
        header.append(f"extern const uint32_t {name}_spirv[];")
        header.append(f"enum {{ {name.upper()}_SPIRV_BYTES = {len(shader['spirv'])} }};")
        source += words_array(f"{name}_spirv", spirv_words, "const") + [""]
        source += words_array(f"{name}_container", container_words) + [""]
        literals = "NULL"
        if shader["literals"]:
            literals = f"{name}_literals"
            source.append(f"static const V4xShaderLiteral {literals}[] = {{")
            for reg, values in shader["literals"]:
                source.append(f"\t{{ {reg}, {{ {', '.join(float_literal(v) for v in values)} }} }},")
            source += ["};", ""]
        resources = "NULL"
        if shader["resources"]:
            resources = f"{name}_resources"
            source.append(f"static const V4xShaderResource {resources}[] = {{")
            for kind, dset, binding, first, count in shader["resources"]:
                source.append(f"\t{{ {RESOURCE_KINDS[kind]}, {dset}, {binding}, {first}, {count} }},")
            source += ["};", ""]
        entries.append(f"\t{{ 0x{shader['hash']:016X}ull, {len(shader['spirv'])}, {name}_container, "
                       f"{len(shader['container'])}, {literals}, {len(shader['literals'])}, {resources}, "
                       f"{len(shader['resources'])} }},")
    source += ["static const V4xShader shaders[] = {"] + entries + ["};", ""]
    source.append(f"const V4xShaderBundle {bundle} = {{ shaders, {len(shaders)} }};")
    header += ["", "#endif"]
    output.with_suffix(".h").write_text("\n".join(header) + "\n", newline="\n")
    output.with_suffix(".c").write_text("\n".join(source) + "\n", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--xost", type=Path, required=True, help="xost's repository (xenos-toolchain)")
    parser.add_argument("--glslang", type=Path, help="glslang, by default xost's tools/glslang/bin/glslang.exe")
    parser.add_argument("--output", type=Path, required=True, help="the C source and header to write, less suffix")
    parser.add_argument("--bundle", default=DEFAULT_BUNDLE, help=f"the bundle's name, by default {DEFAULT_BUNDLE}")
    parser.add_argument("--prefix", default="", help="put before each shader's C names")
    parser.add_argument("--optimize", action="store_true", help="have xost rewrite each program's instructions first")
    parser.add_argument("sources", type=Path, nargs="+")
    args = parser.parse_args()
    glslang = args.glslang or args.xost / "tools" / "glslang" / "bin" / "glslang.exe"
    # Sorted, so the output is the same however the shell lists them.
    args.sources = sorted(args.sources)
    shaders = []
    # Under build/, so the SPIR-V's path is relative too.
    Path("build").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir="build") as directory:
        for source in args.sources:
            spirv_bytes = compile_spirv(glslang, source, directory)
            container, literals, resources = lower(args.xost.resolve(), spirv_bytes, source, args.optimize)
            shaders.append({"name": c_name(source, args.prefix), "spirv": spirv_bytes, "hash": fnv1a_64(spirv_bytes),
                            "container": container, "literals": literals, "resources": resources})
    write_outputs(args.output, shaders, args.sources, args.bundle)


if __name__ == "__main__":
    main()
