#!/usr/bin/env python3
"""Writes vulkan4xenon_test's Aurora points (milestone 18): Aurora's GLSL for its console cases, GX configs drawn as GX
points so each interpolant holds the one vertex's value over the point, and what each should draw.

    gen_aurora_points.py --aurora ../360-ports/aurora-melee --cases <AURORA_GLSL_CONSOLE_DIR>

Aurora's tests/vulkan4xenon_glsl_test.cpp writes the cases' programs (ConsoleCases) as point_<case>.vert and .frag;
they're copied here to tests/shaders/aurora_<case>.vert and .frag. tests/aurora_points.h gets each case's uniform
blocks, push constants and vertex, from Aurora's tools/check_glsl_math.py, where its point lands on the 1280x720
screen, and the colour that tool's reference of the WGSL gives there, map 0 being tests/test_aurora_points.c's
triangle wave. Run tools/build_shaders.py over tests/shaders after it, for the programs' SPIR-V and containers.
"""

import argparse
import math
import re
import shutil
import sys
from pathlib import Path

CASES = ["emboss", "texgen_binormal", "texgen_tangent", "texgen_prior", "texgen_prior_inline", "texgen_zero",
         "texgen_q_zero", "attr_defaults"]
WIDTH, HEIGHT = 1280, 720
POINT_WIDTH = 24.0          # GX's point width, here in pixels: the viewport the game sees is the screen
# Map 0, sampled bilinear and repeating: GRADIENT texels each way, texel (x, y) holding wave(x) in red, wave(y) in
# green and GRADIENT_BLUE in blue. The wave is continuous across the wrap, so no coordinate lands on a texel's edge.
GRADIENT = 256
GRADIENT_BLUE = 128
BLOCKS = 5                  # set 0's uniform pieces, View to Material (Aurora's lib/vulkan4xenon/glsl.hpp)
PUSH_VEC4S = 8              # pos_mtx[3], nrm_mtx[3], line_mask[2]
CORNER_ORDER = [0, 1, 3, 3, 2, 0]   # glsl.cpp's write_corners: corner k is right when odd, lower from 2


def wave(x):
    """A texel's red or green: 255 at both ends, 1 in the middle."""
    return abs(2 * x - (GRADIENT - 1))


def bilinear(c):
    """One axis of map 0 sampled bilinear and repeating at c, Vulkan's texel centres at (i + 0.5) / GRADIENT."""
    t = c * GRADIENT - 0.5
    x0 = math.floor(t)
    w = t - x0
    return ((1.0 - w) * wave(x0 % GRADIENT) + w * wave((x0 + 1) % GRADIENT)) / 255.0


def gradient(u, v):
    return [bilinear(u), bilinear(v), GRADIENT_BLUE / 255.0]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--aurora", type=Path, required=True)
    parser.add_argument("--cases", type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(args.aurora / "tools"))
    import check_glsl_math as ref

    root = Path(__file__).resolve().parent.parent
    lines = ["// Generated by tools/gen_aurora_points.py from Aurora's console cases; don't edit.",
             "#ifndef V4X_AURORA_POINTS_H", "#define V4X_AURORA_POINTS_H", "", '#include "harness.h"',
             '#include "shaders.h"', "", "enum {", f"\tAURORA_POINT_WIDTH = {int(POINT_WIDTH)},",
             f"\tAURORA_GRADIENT = {GRADIENT},", f"\tAURORA_GRADIENT_BLUE = {GRADIENT_BLUE},",
             f"\tAURORA_BLOCKS = {BLOCKS},", f"\tAURORA_PUSH_VEC4S = {PUSH_VEC4S},", "\tAURORA_MAX_ATTRIBUTES = 6,",
             "\tAURORA_CORNERS = 6,", "};", "",
             "// An attribute of the point's vertex: its location and value, a corner's at the corner's location.",
             "typedef struct {", "\tuint32_t location;", "\tuint32_t components;", "\tfloat value[3];",
             "\tbool corner;", "} AuroraAttribute;", "",
             "typedef struct {", "\tconst char *name;", "\tconst uint32_t *vertex_spirv;", "\tuint32_t vertex_bytes;",
             "\tconst uint32_t *fragment_spirv;", "\tuint32_t fragment_bytes;",
             "\t// Set 0's blocks, each its vec4s in their order; a block neither program reads has none.",
             "\tconst float *blocks[AURORA_BLOCKS];", "\tuint32_t block_vec4s[AURORA_BLOCKS];",
             "\tfloat push[AURORA_PUSH_VEC4S][4];", "\tAuroraAttribute attributes[AURORA_MAX_ATTRIBUTES];",
             "\tuint32_t attribute_count;", "\t// The point's middle pixel and the colour drawn there.",
             "\tuint32_t x;", "\tuint32_t y;", "\tRgb want;", "} AuroraPoint;", ""]
    table = []
    for case in CASES:
        texts = {}
        for stage in ("vert", "frag"):
            source = args.cases / f"point_{case}.{stage}"
            target = root / "tests" / "shaders" / f"aurora_{case}.{stage}"
            shutil.copyfile(source, target)
            texts[stage] = source.read_text()

        values = ref.uniforms()
        values["uview.viewport_sizes"] = [[float(WIDTH), float(HEIGHT), float(WIDTH), float(HEIGHT)]]
        values["uview.line_params"] = [[POINT_WIDTH, 0.0, 0.0, 0.0]]
        if case == "texgen_q_zero":
            values["uview.postmtx"] = ref.POST_Q_ZERO
        blocks = []
        for binding in range(BLOCKS):
            members = None
            for text in texts.values():
                if f"binding = {binding}, std140" in text:
                    var, found = ref.block_var(text, binding)
                    if members is None or len(found) > len(members[1]):
                        members = (var, found)
            rows = []
            if members:
                var, found = members
                for name, count in found:
                    data = values.get(f"{var}.{name}", [])
                    rows += [list(data[i]) + [0.0] * (4 - len(data[i])) if i < len(data) else [0.0] * 4
                             for i in range(count)]
            blocks.append(rows)
        push = [list(r) for r in ref.pos_matrix(ref.CURRENT_PNMTX)] + [list(r) for r in ref.nrm_matrix(ref.CURRENT_PNMTX)]
        push += [[0.0] * 4, [0.0] * 4]

        position = {"texgen_zero": [0.0, 0.0, 0.0], "attr_defaults": [9.0, 9.0, 9.0]}.get(case, ref.POSITION)
        inputs = {"in_pos": position, "in_nrm": ref.NORMAL, "in_binrm": ref.BINORMAL, "in_tangent": ref.TANGENT,
                  "in_tex0_uv": ref.TEX0}
        attributes = []
        for location, kind, name in re.findall(r"layout\(location = (\d+)\) in (\w+) (\w+);", texts["vert"]):
            components = {"float": 1, "vec2": 2, "vec3": 3}[kind]
            if name == "in_corner":
                attributes.append((int(location), components, [0.0, 0.0, 0.0], True))
            else:
                attributes.append((int(location), components, list(inputs[name]) + [0.0] * (3 - len(inputs[name])),
                                   False))

        drawn_at = [0.0, 0.0, 0.0] if case in ("texgen_zero", "attr_defaults") else ref.POSITION
        mv = ref.rows3x4(ref.pos_matrix(ref.CURRENT_PNMTX), drawn_at + [1.0])
        clip = [ref.dot(row, mv + [1.0]) for row in ref.PROJ]
        x = (clip[0] / clip[3] * 0.5 + 0.5) * WIDTH
        y = (0.5 - 0.5 * clip[1] / clip[3]) * HEIGHT
        uvs = ref.ref_texgen_uvs(case)
        rasterized = ref.CHANNEL_COLORS[1][:3]
        if case == "texgen_prior":
            color = ref.mul(gradient(*uvs[1]), gradient(*uvs[0]))
        else:
            color = ref.mul(gradient(*uvs[0]), rasterized)
        want = [int(round(ref.clamp(c) * 255.0)) for c in color]

        prefix = f"aurora_{case}"
        for binding, rows in enumerate(blocks):
            if rows:
                lines.append(f"static const float {prefix}_block{binding}[] = {{")
                lines += ["\t" + ", ".join(f"{float(c)!r}f" for c in row) + "," for row in rows]
                lines.append("};")
        lines.append("")
        block_refs = ", ".join(f"{prefix}_block{b}" if rows else "NULL" for b, rows in enumerate(blocks))
        block_counts = ", ".join(str(len(rows)) for rows in blocks)
        push_text = ", ".join("{ " + ", ".join(f"{float(c)!r}f" for c in row) + " }" for row in push)
        attribute_text = ", ".join(
            f"{{ {loc}, {comp}, {{ {', '.join(f'{float(c)!r}f' for c in value)} }}, {'true' if corner else 'false'} }}"
            for loc, comp, value, corner in attributes)
        table.append(f"\t{{ \"{case}\", {prefix}_vert_spirv, {prefix.upper()}_VERT_SPIRV_BYTES, {prefix}_frag_spirv, "
                     f"{prefix.upper()}_FRAG_SPIRV_BYTES, {{ {block_refs} }}, {{ {block_counts} }}, {{ {push_text} }}, "
                     f"{{ {attribute_text} }}, {len(attributes)}, {int(x)}, {int(y)}, "
                     f"{{ {want[0]}, {want[1]}, {want[2]} }} }},")
        print(f"{case}: point at ({int(x)}, {int(y)}), sampled at {[[round(c, 4) for c in uv] for uv in uvs]}, "
              f"wants {want}")
    lines += ["static const AuroraPoint aurora_points[] = {"] + table + ["};", "", "#endif", ""]
    (root / "tests" / "aurora_points.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
